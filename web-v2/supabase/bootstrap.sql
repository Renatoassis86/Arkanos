-- ============================ CONTEÚDO ======================================

create table if not exists public.quiz_subjects (
  id         bigint generated by default as identity primary key,
  name       varchar(100) not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_grades (
  id         bigint generated by default as identity primary key,
  name       varchar(50) not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_assessments (
  id         bigint generated by default as identity primary key,
  name       varchar(100) not null,
  grade_id   bigint not null references public.quiz_grades(id) on delete cascade,
  subject_id bigint not null references public.quiz_subjects(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (name, grade_id, subject_id)
);

create table if not exists public.quiz_topics (
  id            bigint generated by default as identity primary key,
  subject_id    bigint not null references public.quiz_subjects(id) on delete cascade,
  grade_id      bigint references public.quiz_grades(id) on delete set null,
  assessment_id bigint references public.quiz_assessments(id) on delete set null,
  name          varchar(100) not null,
  created_at    timestamptz not null default now(),
  unique (subject_id, grade_id, assessment_id, name)
);

create table if not exists public.quiz_questions (
